import { chromium } from 'playwright';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const out=fileURLToPath(new URL('.',import.meta.url));
const browser=await chromium.launch({headless:true,channel:'chrome'});
const errors=[];
const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
page.on('pageerror',error=>errors.push(error.message));
page.on('console',message=>{if(message.text().includes('Interactive globe unavailable'))errors.push(message.text());});
const home=process.env.ARCHIVE_PREVIEW_URL ?? 'http://127.0.0.1:4329/';
await page.goto(home);
await page.locator('#globe-canvas[tabindex="0"]').waitFor();
assert.match(await page.locator('[data-surprise-help]').innerText(),/23 stories at random/);
await page.screenshot({path:out+'/intro-desktop.png'});
await page.locator('#start').scrollIntoViewIfNeeded();
await page.screenshot({path:out+'/start-desktop.png'});
await page.locator('[data-search-input]').fill('no-such-story-zzzz');
assert.equal(await page.locator('[data-surprise]').isDisabled(),true);
assert.match(await page.locator('[data-surprise-help]').innerText(),/No matching stories/);
await page.locator('[data-search-input]').fill('Junior');
assert.match(await page.locator('[data-surprise-help]').innerText(),/one story matching/);
await page.locator('[data-surprise]').click();
await page.waitForURL('**/archive/junior-akinola-belonging/');
assert.equal(await page.locator('video').count(),3);
await page.goto(home);
await page.locator('#globe-canvas[tabindex="0"]').waitFor();
await page.locator('.discover-panel [data-year-button="2024"]').click();
await page.locator('.discover-panel [data-format-button="watch"]').click();
await page.locator('.discover-panel [data-theme-button="Live moments"]').click();
const filtered=await page.locator('[data-result-link]:not([hidden])').evaluateAll(links=>links.map(link=>link.href));
assert.ok(filtered.length>1&&filtered.length<23);
assert.match(await page.locator('[data-surprise-help]').innerText(),new RegExp(`${filtered.length} matching stories`));
await page.evaluate(()=>{Math.random=()=>.999999;});
await page.locator('[data-surprise]').click();
await page.waitForURL(filtered.at(-1));
await page.goto(home);
await page.locator('#globe-canvas[tabindex="0"]').waitFor();
await page.locator('[data-enter-immersive]').click();
if(await page.locator('[data-toggle-rail]').getAttribute('aria-expanded')==='true') await page.locator('[data-toggle-rail]').click();
const bounds=await page.locator('#globe-canvas').boundingBox();
for(const axis of ['x','y'])for(let i=0;i<3;i++){
 const start={x:bounds.x+bounds.width*.2,y:bounds.y+bounds.height*.2};
 const end={x:axis==='x'?bounds.x+bounds.width*.8:start.x,y:axis==='y'?bounds.y+bounds.height*.8:start.y};
 await page.mouse.move(start.x,start.y);await page.mouse.down();await page.mouse.move(end.x,end.y,{steps:20});await page.mouse.up();
}
await page.locator('#globe-canvas').focus();
for(let i=0;i<24;i++)await page.keyboard.press('Shift+ArrowUp');
for(let i=0;i<24;i++)await page.keyboard.press('Shift+ArrowRight');
await page.keyboard.press('0');
if(await page.locator('[data-toggle-rail]').getAttribute('aria-expanded')==='false') await page.locator('[data-toggle-rail]').click();
await page.locator('[data-immersive-story="gloria-rose-design"]').click();
assert.match(await page.locator('[data-preview-title]').innerText(),/Gloria Rose/i);
await page.locator('[data-close-preview]').click();
await page.locator('[data-hide-rail]').click();
await page.screenshot({path:out+'/globe-desktop.png'});
await page.locator('[data-close-immersive]').click();
await page.goto(home+'archive/temne-making-together/');
assert.match(await page.locator('.hero-photo').getAttribute('src'),/temne-20.webp/);
assert.equal(await page.locator('video').count(),2);
assert.equal(await page.locator('.gallery-tile').count(),6);
await page.locator('.hero-bottom [data-photo-index="0"]').click();
assert.match(await page.locator('[data-photo-title]').innerText(),/laughter/i);
await page.locator('[data-photo-close]').click();
await page.screenshot({path:out+'/temne-desktop.png'});
const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true,reducedMotion:'reduce'});
mobile.on('pageerror',error=>errors.push(error.message));
await mobile.goto(home);
await mobile.locator('#globe-canvas[tabindex="0"]').waitFor();
assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
await mobile.screenshot({path:out+'/intro-mobile.png'});
await mobile.locator('.surprise-choice').scrollIntoViewIfNeeded();
await mobile.screenshot({path:out+'/start-mobile.png'});
await mobile.locator('[data-enter-immersive]').click();
await mobile.locator('[data-toggle-rail]').click();
await mobile.locator('[data-immersive-story="junior-akinola-belonging"]').click();
assert.match(await mobile.locator('[data-preview-title]').innerText(),/Junior Akinola/i);
await mobile.locator('[data-close-immersive]').click();
const fallback=await browser.newPage({reducedMotion:'reduce'});
await fallback.addInitScript(()=>{HTMLCanvasElement.prototype.getContext=()=>null;});
await fallback.goto(home);
await fallback.locator('[data-surprise]:not([disabled])').waitFor();
await fallback.locator('[data-search-input]').fill('Junior');
await fallback.locator('[data-surprise]').click();
await fallback.waitForURL('**/archive/junior-akinola-belonging/');
assert.deepEqual(errors,[]);
const result={passed:true,filteredRandomPool:filtered.length,checks:['random navigation respects combined filters','single result and empty result explanations','desktop and mobile immersive selection','repeated pointer drags, keyboard full turns on both axes and reset','TEMNE original cover, two films and six images','mobile overflow','random discovery without WebGL'],browserErrors:errors};
await fs.writeFile(out+'/browser-checks.json',JSON.stringify(result,null,2)+'\n');
console.log(JSON.stringify(result,null,2));
await browser.close();
